import { spawn } from 'node:child_process';
import path from 'node:path';

export interface ForecastResult {
  history: any[];
  forecast: any[];
  baselineROI: number;
  scenarioROI: number;
  confidenceLow: number;
  confidenceHigh: number;
  trend: string;
  volatility: number;
  seasonality: number;
  forecastMethod: string;
  selectionReason?: string;
  explanation: string;
}

function buildScriptPath() {
  // API runs from apps/api; Python agent lives at apps/ml/m06/forecast_agent.py
  const cwd = process.cwd();
  return path.resolve(cwd, '..', 'ml', 'm06', 'forecast_agent.py');
}

export async function invokePythonAgent(
  campaignId: number,
  forecastWindow: string,
  spendMultiplier: number,
  forecastMethod = 'auto',
): Promise<ForecastResult> {
  const pythonExec = process.env.PYTHON_EXECUTABLE || 'python';
  const scriptPath = buildScriptPath();

  return new Promise<ForecastResult>((resolve, reject) => {
    const args = [
      scriptPath,
      '--campaign', String(campaignId),
      '--window', forecastWindow,
      '--multiplier', String(spendMultiplier),
      '--method', forecastMethod,
    ];

    const child = spawn(pythonExec, args, {
      cwd: path.dirname(scriptPath),
      stdio: ['ignore', 'pipe', 'pipe'],
    });

    let stdout = '';
    let stderr = '';

    const timeout = setTimeout(() => {
      child.kill();
      reject(new Error('forecast_agent_timeout'));
    }, 60_000);

    child.stdout.on('data', (chunk) => {
      stdout += chunk.toString();
    });

    child.stderr.on('data', (chunk) => {
      stderr += chunk.toString();
    });

    child.on('error', (err) => {
      clearTimeout(timeout);
      reject(err);
    });

    child.on('close', (code) => {
      clearTimeout(timeout);
      if (code !== 0) {
        const msg = stderr || `forecast_agent_exit_code_${code}`;
        reject(new Error(msg));
        return;
      }

      try {
        const parsed = JSON.parse(stdout || '{}');
        const result: ForecastResult = {
          history: Array.isArray(parsed.history) ? parsed.history : [],
          forecast: Array.isArray(parsed.forecast) ? parsed.forecast : [],
          baselineROI: Number(parsed.baseline_roi || 0),
          scenarioROI: Number(parsed.scenario_roi || 0),
          confidenceLow: Number(parsed.confidence_low || 0),
          confidenceHigh: Number(parsed.confidence_high || 0),
          trend: typeof parsed.trend === 'string' ? parsed.trend : 'flat',
          volatility: Number(parsed.volatility || 0),
          seasonality: Number(parsed.seasonality || 0),
          forecastMethod: typeof parsed.forecast_method === 'string' ? parsed.forecast_method : forecastMethod,
          selectionReason: typeof parsed.selection_reason === 'string' ? parsed.selection_reason : undefined,
          explanation: typeof parsed.explanation === 'string' ? parsed.explanation : 'Forecast generated by Python agent.',
        };
        resolve(result);
      } catch (e) {
        reject(new Error('forecast_agent_invalid_json'));
      }
    });
  });
}

